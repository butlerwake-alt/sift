"""Build research_data.js for research.html from research.json (descriptions) and a frozen backtest run.
Not touched by build_data.py, so the twice-daily publish keeps it. Re-run only when a NEW experiment is added.
Every strategy must carry a 'why' (required; see README)."""
import json, os, shutil
HERE = os.path.dirname(os.path.abspath(__file__))
R = json.load(open(f"{HERE}/research.json"))
RUN = R["run"]
res = json.load(open(f"{RUN}/results/results.json")); curves = json.load(open(f"{RUN}/results/curves_weekly.json"))
man = json.load(open(f"{RUN}/data/manifest.json"))
def monthly(pts):
    out = {}; [out.__setitem__(d[:7], [d, v]) for d, v in pts]
    m = list(out.values()); return [pts[0]] + [p for p in m if p[0] != pts[0][0]]
def pct(x): return ("+" if x > 0 else "−" if x < 0 else "") + "{:,.1f}%".format(abs(x))
out = []
for s in R["strategies"]:
    k = s["key"]; r = res[k]; f = r["windows"]["full"]; n = r["windows"]["recent"]
    fo, fb, no, nb = f["open"], f["buy_hold"], n["open"], n["buy_hold"]
    s = dict(s)
    s["verdict"] = r["verdict"]; s["ddLimit"] = r["dd_limit_10pct"]; s["feePct"] = r["fee_per_side_pct"]
    s["full"] = {"from": fo["first"], "to": fo["last"], "strat": fo, "hold": fb, "closeFill": f["close"], "doubleFeeReturn": f["open_double_fee_total_return_pct"]}
    s["recent"] = {"from": no["first"], "to": no["last"], "strat": no, "hold": nb}
    s["curve"] = monthly(curves[k]); s["holdCurve"] = monthly(curves[k + "__bh"])
    if not s.get("why"):
        s["why"] = ("Picked for testing because it is widely shared online with fixed, checkable rules (source linked). "
                    "New backtest, next-open fills, fees included: {} to {}: {} (max drawdown {}%) vs buy-and-hold {} ({}%). "
                    "Recent window {} to {}: {} vs buy-and-hold {}. Verdict by the pre-written rule: {}. 10% drawdown limit: {}.").format(
                    fo["first"], fo["last"], pct(fo["total_return_pct"]), fo["max_dd_pct"], pct(fb["total_return_pct"]), fb["max_dd_pct"],
                    no["first"], no["last"], pct(no["total_return_pct"]), pct(nb["total_return_pct"]), r["verdict"], r["dd_limit_10pct"])
    for req in ("name", "plain", "sources", "rules", "why", "verdict"):
        assert s.get(req), f"{k}: missing required field {req}"
    out.append(s)
order = {"Promising": 0, "Mixed": 1, "Failed": 2}
out.sort(key=lambda s: (order[s["verdict"]], -(s["full"]["strat"]["sharpe"] - s["full"]["hold"]["sharpe"])))
data = {"title": R["title"], "label": R["label"], "method": R["method"], "dataManifest": man, "strategies": out}
js = "/* Generated by build_research.py from research.json and the frozen NEW EXPERIMENT run in {}. Historical backtests only. */\nconst RESEARCH = {};\n".format(os.path.basename(RUN), json.dumps(data, ensure_ascii=False, separators=(",", ":")))
open(f"{HERE}/research_data.js", "w").write(js)
# public copy of the code and outputs (not the raw price files) so anyone can check the numbers
dst = f"{HERE}/research/{os.path.basename(RUN)}"; os.makedirs(dst, exist_ok=True)
for rel in ["fetch.py", "backtest.py", "crosscheck_vbt.py", "README.md", "data/manifest.json", "results/results.json", "results/crosscheck_vbt.txt"]:
    src = f"{RUN}/{rel}"
    if not os.path.exists(src):
        continue
    target = f"{dst}/{os.path.basename(rel)}"
    if os.path.abspath(src) == os.path.abspath(target):
        continue  # run already lives under research/
    shutil.copy(src, target)
print("research_data.js:", len(out), "strategies,", len(js), "bytes")
